#!/usr/bin/env bash
#
# Regenerate 20-results-ddl.sql: WebAPI's results-schema DDL for the
# production schema names, fetched from the dev stack (chi/devstack), which
# must run the same image version as production.
#
#   chi/deploy/webapi/sql/make-results-ddl.sh
#
# Upstream 3.0.0's DDL creates no HERACLES_* / heracles_* tables but still
# indexes them, so those statements are dropped here; otherwise the script
# stops at the first one and later indexes are never created.
set -euo pipefail
cd "$(dirname "$0")"

RESULTS=${RESULTS:-webapi_results}
TEMP=${TEMP:-webapi_temp}
VOCAB=${VOCAB:-dbo}
V=${V:-https://dev.lastchance.pub}
OUT=20-results-ddl.sql

eval "$(../../../devstack/session.sh developer)"   # sets JAR, JWT
VERSION=$(curl -fsS -b "$JAR" -H "Authorization: Bearer $JWT" "$V/WebAPI/info" |
  python3 -c 'import sys,json; print(json.load(sys.stdin)["version"])')

DDL=$(curl -fsS -b "$JAR" -H "Authorization: Bearer $JWT" -G "$V/WebAPI/ddl/results" \
  --data-urlencode "dialect=sql server" --data-urlencode "schema=$RESULTS" \
  --data-urlencode "vocabSchema=$VOCAB" --data-urlencode "tempSchema=$TEMP" \
  --data-urlencode "initConceptHierarchy=true")

{
  echo "-- WebAPI results-schema DDL for SQL Server: results=$RESULTS temp=$TEMP vocabulary=$VOCAB."
  echo "-- Generated by make-results-ddl.sh from WebAPI $VERSION; do not edit by hand."
  echo "-- Run after 10-schemas.sql, as the WebAPI database user (which also checks"
  echo "-- its permissions):  sqlcmd -S <server> -d <database> -U <user> -b -i $OUT"
  echo "-- Upstream's indexes on the never-created Heracles tables are removed, and"
  echo "-- the remaining CREATE INDEX statements are guarded so the script can be re-run."
  grep -v -i -E "^CREATE INDEX .* ON ${RESULTS}\.heracles_" <<<"$DDL" |
    sed -E "s/^CREATE INDEX ([A-Za-z0-9_]+) ON ([A-Za-z0-9_.]+) (.*)$/IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = '\1' AND object_id = OBJECT_ID('\2'))\n  CREATE INDEX \1 ON \2 \3/"
} > "$OUT"

echo "wrote $OUT ($(grep -c -i '^CREATE TABLE' "$OUT") tables, $(grep -c -i '^  CREATE INDEX' "$OUT") indexes;" \
  "dropped $(grep -c -i -E "^CREATE INDEX .* ON ${RESULTS}\.heracles_" <<<"$DDL") Heracles indexes)"
